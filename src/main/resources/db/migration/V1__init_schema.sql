CREATE TABLE IF NOT EXISTS users_telegram (
    id BIGINT NOT NULL PRIMARY KEY,
    first_name VARCHAR(255),
    registered_at TIMESTAMP(6) WITHOUT TIME ZONE,
    target_calories INTEGER,
    target_carbs INTEGER,
    target_fat INTEGER,
    target_protein INTEGER,
    username VARCHAR(255),
    approved BOOLEAN
);

CREATE TABLE IF NOT EXISTS meals (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    bot_message_id INTEGER,
    calories INTEGER,
    carbs DOUBLE PRECISION,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    description VARCHAR(255),
    fat DOUBLE PRECISION,
    protein DOUBLE PRECISION,
    raw_input TEXT,
    user_message_id INTEGER,
    user_id BIGINT NOT NULL REFERENCES users_telegram(id)
);

CREATE INDEX IF NOT EXISTS idx_meal_user_created ON meals (user_id, created_at);

CREATE TABLE IF NOT EXISTS workout_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL PRIMARY KEY,
    bot_message_id INTEGER,
    created_at TIMESTAMP(6) WITHOUT TIME ZONE,
    description VARCHAR(255),
    duration_minutes INTEGER,
    exercises_json TEXT,
    raw_input TEXT,
    user_message_id INTEGER,
    user_id BIGINT NOT NULL REFERENCES users_telegram(id)
);

CREATE INDEX IF NOT EXISTS idx_workout_user_created ON workout_sessions (user_id, created_at);
